#!/bin/sh
set -eu

DISPLAY_NUM="${DISPLAY#:}"
SCREEN_WIDTH="${SCREEN_WIDTH:-1280}"
SCREEN_HEIGHT="${SCREEN_HEIGHT:-900}"
SCREEN_DEPTH="${SCREEN_DEPTH:-24}"
NOVNC_PORT="${NOVNC_PORT:-6080}"
VNC_PORT="${VNC_PORT:-5900}"
TARGET_URL="${TARGET_URL:-http://localhost:8080/jci/gui/index.html}"
OPERA_PROFILE="${OPERA_PROFILE:-/tmp/opera-profile}"

mkdir -p "${OPERA_PROFILE}/toolbar" "${HOME:-/root}/.config/openbox"

# Register firmware fonts if jci/fonts/CHN is mounted into /jci/fonts/CHN or /usr/local/share/fonts/jci.
export FREETYPE_FONT_SET=YES
export OPERA_FONTS=/jci/fonts/CHN
if [ -d /jci/fonts/CHN ]; then
    cat > /etc/fonts/local.conf <<'EOF'
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<fontconfig>
  <dir>/jci/fonts/CHN</dir>
</fontconfig>
EOF
    fc-cache -f || true
elif [ -d /usr/local/share/fonts/jci ]; then
    fc-cache -f || true
fi

# Copy Opera's default toolbar config without the web search field (tbs_MainSearch)
# or Wand password manager button (tbb_Wand).
if [ ! -f "${OPERA_PROFILE}/toolbar/standard_toolbar.ini" ] && [ -f /opt/opera/share/opera/ui/standard_toolbar.ini ]; then
    grep -vE 'tbs_MainSearch|tbb_Wand' /opt/opera/share/opera/ui/standard_toolbar.ini > "${OPERA_PROFILE}/toolbar/standard_toolbar.ini"
fi

# Pre-seed Opera preferences matching mzd-emu/jci/opera/opera_home/opera.ini
# where applicable, while keeping Opera's menu/toolbar/DevTools usable and
# disabling desktop-only features (Speed Dial, Mail, Unite, Turbo, Wand, etc.).
if [ ! -f "${OPERA_PROFILE}/operaprefs.ini" ]; then
    cat > "${OPERA_PROFILE}/operaprefs.ini" <<EOF
Opera Preferences version 2.1
; Do not edit this file while Opera is running
; This file is stored in UTF-8 encoding

[Extensions]
Scripting=1
Plugins=1
Frames=1

[System]
DisableTextSelect=1

[Security Prefs]
Enable SSL v3=1
Enable TLS v1.0=1
OCSP Validate Certificates=1

[User Prefs]
Preferences Version=6
; CMU opera.ini settings
Enable Webfonts=0
Video RAM Limit=98304
Enable WebGL=1
Warn Insecure Form=0
Enable Cookies=3
Document Mode=1
Show Images=3
Show ScrollBars=1
Scroll Is Pan=0
Offline Mode=0
Scale=100
Max Window History Lines=10
Max Global History Lines=100
Ignore Unrequested Popups=1
Home URL=${TARGET_URL}
Browser JavaScript=2
SSR Max Width=240
Turbo Mode=0
Enable Trust Rating=0
Enable Gesture=0
Show Gesture UI=0
Enable WebSockets=1
Reverse button flipping=0
Show IME Password=0
User JavaScript=0
Time Update Interval=200

; Desktop container UI & feature trimming (keep menu/tabs/address bar/DevTools)
Toolbar Configuration=${OPERA_PROFILE}/toolbar/standard_toolbar.ini
Startup Type=2
Speed Dial State=3
Show Add Speed Dial Button=0
Enable Wand=0
Wand Autosubmit=0
Show Search Suggestions In Addressfield Dropdown=0
Opera Turbo Mode=0
Show Opera Turbo Info=0
Spellcheck enabled by default=0
Enable Tab Thumbnails=0
Use Thumbnails Inside Tabs=0
Use Thumbnails in Tab Tooltips=0
Use Thumbnails in Window Cycle=0
Show Default Browser Dialog=0
Show E-mail Client=0
Automatic Select=0
Restore Mode=1
Show Setupdialog On Start=0
Show Startup Dialog=0
Show Exit Dialog=0
Show New Opera Dialog=0
Show Problem Dialog=0
Enable Unite=0
Enable Usage Statistics=0
Check For New Opera=0
Auto Update State=0
Disable Widget Runtime=1

[Network]
Enable Do Not Track Header=0

[Disk Cache]
Enabled=0
Size=2000
Cache Docs=1
