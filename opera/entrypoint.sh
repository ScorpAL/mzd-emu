[Install]
Newest Used Version=12.16.1860
Newest Used Beta Name=
First Used Version=12.16.1860
First Run Timestamp=1795784777

[Developer Tools]
Developer Tools URL=http://dragonfly.op-test.net/
EOF
fi

# Strip window decorations and maximize Opera inside the virtual display.
cat > "${HOME:-/root}/.config/openbox/rc.xml" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<openbox_config xmlns="http://openbox.org/3.4/rc">
  <applications>
    <application class="*">
      <decor>no</decor>
      <maximized>true</maximized>
    </application>
  </applications>
</openbox_config>
EOF

Xvfb "${DISPLAY}" -screen 0 "${SCREEN_WIDTH}x${SCREEN_HEIGHT}x${SCREEN_DEPTH}" -ac -noreset &
XVFB_PID=$!

# Wait for Xvfb socket
i=0
while [ ! -S "/tmp/.X11-unix/X${DISPLAY_NUM}" ]; do
    i=$((i + 1))
    if [ "${i}" -gt 50 ]; then
        echo "Xvfb failed to start on ${DISPLAY}" >&2
        exit 1
    fi
    sleep 0.1
done

openbox &
OPENBOX_PID=$!

x11vnc -display "${DISPLAY}" -rfbport "${VNC_PORT}" -forever -shared -nopw -quiet &
VNC_PID=$!

websockify --web=/usr/share/novnc "${NOVNC_PORT}" "localhost:${VNC_PORT}" &
NOVNC_PID=$!

cleanup() {
    kill "${NOVNC_PID}" "${VNC_PID}" "${OPENBOX_PID}" "${XVFB_PID}" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

# shellcheck disable=SC2086
exec /opt/opera/opera \
    -pd "${OPERA_PROFILE}" \
    ${OPERA_ARGS:-} \
    "${TARGET_URL}"
